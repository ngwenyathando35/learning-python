firstNumber = int(input("Please enter an integer >> "))
secondNumber = int(input("Please enter another integer >> "))

sum = firstNumber + secondNumber
difference = firstNumber - secondNumber
average = sum/2

print(f"{firstNumber} + {secondNumber} is {sum}")
print(f"{firstNumber} - {secondNumber} is {difference}")
print(f"The average of {firstNumber} and {secondNumber} is {average}")